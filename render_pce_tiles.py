"""Compatibility shim for the packaged PCE tile renderer."""

from cyber_oedo.graphics import render_pce_tiles as _implementation
from cyber_oedo.graphics.render_pce_tiles import *  # noqa: F401,F403

main = _implementation.main


def __getattr__(name: str):
    """Forward compatibility lookups to the packaged implementation."""

    return getattr(_implementation, name)


def __dir__() -> list[str]:
    """Expose the union of shim and implementation names."""

    return sorted(set(globals()) | set(dir(_implementation)))


if __name__ == "__main__":
    raise SystemExit(main())
